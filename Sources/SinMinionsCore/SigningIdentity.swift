import Foundation

/// Отпечатки сертификатов, которыми разрешено подписывать обновления.
///
/// Подпись сборки — самоподписанный сертификат «SinMinions Signing», а не Developer ID:
/// программа разработчика не оформлена, а стабильная подпись нужна для того, чтобы
/// выданный «Универсальный доступ» переживал обновления. Поэтому доверие к обновлению
/// опирается на этот список отпечатков (SHA-1 листового сертификата).
///
/// Список нужен, чтобы сертификат можно было сменить без потери обновлений:
/// в переходной версии остаются оба отпечатка — старый и новый, — после чего старый убирается.
/// Пустой список не разрешает ничего: проверка подписи в этом случае провалится.
public enum SigningIdentity {
    public static let leafHashes: [String] = [
        "6AF0CB9419CE2D6A8AFD7F5460F1EA51DA557FAE",
    ]

    /// Требование codesign, по которому проверяется подпись скачанного обновления.
    public static var requirement: String {
        leafHashes
            .map { #"certificate leaf = H"\#($0)""# }
            .joined(separator: " or ")
    }

    /// Подходит ли отпечаток листового сертификата (регистр не важен).
    public static func accepts(leafHash: String) -> Bool {
        leafHashes.contains(leafHash.uppercased())
    }
}
