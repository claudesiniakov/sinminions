    public static func pool(_ kind: PhraseKind, hour: Int, character: CompanionCharacter = .f) -> [String] {
        if character == .v {
            switch kind {
            case .click: return [
                "я на связи!",
                "есть минутка на идею?",
                "привет! как тебе мой новый заголовок?",
                "секунду, переверну стикер чистой стороной",
                "да, слушаю. карандаш наготове",
            ]
            case .wake: return [
                "снова в эфире!",
                "я проснулась. на чём мы остановились?",
                "доброе! дай минутку найти блокнот",
            ]
            case .shooed: return [
                "увидимся после перерыва",
                "подвинусь. здесь тебе хватит места?",
            ]
            case .scared: return [
                "вот это резкий рост!",
                "ой, чуть карандаш не уронила!",
            ]
            case .searching: return [
                "где же мой бриф?",
                "ищу зацепки для кампании…",
                "проверю, что тут есть",
                "кто-нибудь видел жёлтый стикер?",
                "точно помню: карандаш лежал рядом с графиком",
            ]
            case .charging: return [
                "питание подключено",
                "заряд растёт",
                "кабель на месте. можно дописать бриф",
            ]
            case .lowBattery: return [
                "заряда маловато",
                "пора искать розетку",
                "заряд на исходе. где у нас кабель?",
            ]
            case .updateAvailable: return [
                "есть обновление — загляни в меню",
                "в меню ждёт новая версия. заглянем?",
            ]
            case .needAccess, .spotlightOff: return byKind[kind] ?? []
            case .teleport: return [
                "а вот и я",
                "оп! а вот и другой край экрана",
                "блокнот со мной? тогда всё в порядке",
            ]
            case .curious: return [
                "что тут у тебя?",
                "куда ведёшь? я с тобой",
                "о, покажи поближе",
            ]
            case .boo: return [
                "бу!",
                "нашлось место, где меня никто не ждал!",
            ]
            case .playing: return ["есть!"]
            case .ambient: return [
                "кому это будет полезно?",
                "проверим гипотезу?",
                "а что говорят цифры?",
                "у этого заголовка есть характер",
                "записала идею на полях брифа",
                "интересно, почему люди нажимают именно сюда?",
                "первый черновик готов",
                "оставим место для неожиданной идеи",
                "а если спросить самих читателей?",
                "кажется, придумала конец для этой истории",
                "мне нравится этот оттенок розового",
                "рисовала воронку, получилась ваза",
                "нашла короткое слово вместо трёх длинных",
                "у меня три варианта. любимый, конечно, четвёртый",
                "можно я оставлю этот стикер здесь?",
                "придумала слоган. скажу вслух и послушаю, как звучит",
                "после прогулки заголовки пишутся легче",
            ]
            }
        }
        if character == .ab {
            // У стража свой набор целиком: реплики призрака с отсылками к Fallout сюда не попадают.
            if kind == .ambient { return guardAmbient + guardTimeOfDay(hour: hour) }
            return guardByKind[kind] ?? guardAmbient
        }
        return kind == .ambient ? general + timeOfDay(hour: hour) : (byKind[kind] ?? general)
    }

    private var decks: [String: [String]] = [:]
    private var last: String?
    private let shuffle: ([String]) -> [String]
    public let character: CompanionCharacter

    public init(character: CompanionCharacter = .f, shuffle: @escaping ([String]) -> [String] = { $0.shuffled() }) {
        self.character = character
        self.shuffle = shuffle
    }

    /// Следующая реплика: внутри одного повода фразы не повторяются, пока не пройден весь набор.
    public mutating func next(_ kind: PhraseKind, hour: Int) -> String {
        let key = kind == .ambient ? "ambient-\(Self.timeOfDay(hour: hour).first ?? "")" : kind.rawValue
        var deck = decks[key] ?? []
        if deck.isEmpty {
            deck = shuffle(Self.pool(kind, hour: hour, character: character))
            // Новая колода не должна начинаться с только что сказанного.
            if deck.count > 1, deck.last == last { deck.swapAt(0, deck.count - 1) }
        }
        let phrase = deck.removeLast()
        decks[key] = deck
        last = phrase
        // Реплики хранятся по-русски; на экран — на языке интерфейса.
        return tr(phrase)
    }
